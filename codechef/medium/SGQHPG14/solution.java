class Codechef {
    public static void main(String[] args) {
        int remainingAttempts = 3; // Initial attempts count

        // Simulating attempts using post-decrement
        System.out.println("Attempts left: " + remainingAttempts--);
        System.out.println("Attempts left: " + remainingAttempts--);
        System.out.println("Attempts left: " + remainingAttempts--);
    }
}
